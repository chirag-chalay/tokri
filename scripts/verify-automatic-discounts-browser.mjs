import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright-core'

const db = new URL(process.env.DATABASE_URL || 'mysql://invalid')
assert.equal(db.hostname, '127.0.0.1'); assert.equal(db.port, '13317'); assert.equal(db.pathname, '/tokri_discounts_test')
const { prisma } = await import('../server/src/lib/prisma.js')
const { replaceCart } = await import('../server/src/services/cart.js')
const { signCustomerToken } = await import('../server/src/services/jwt.js')
const web = 'http://127.0.0.1:3037'
const backend = 'http://127.0.0.1:5237'
const root = `${backend}/tokri-backoffice`
const shots = 'docs/automatic-discounts'
await mkdir(shots, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || '/usr/bin/google-chrome', headless: true })
const errors = []
try {
  const adminContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const admin = await adminContext.newPage()
  admin.on('pageerror', (error) => errors.push(error.message))
  await admin.goto(`${root}/login`)
  await admin.locator('input[name="email"]').fill('admin@tokriii.com')
  await admin.locator('input[name="password"]').fill('admin123')
  await admin.getByRole('button', { name: 'Sign in', exact: true }).click()
  await admin.waitForURL((url) => !url.pathname.includes('login'))
  await admin.goto(`${root}/resources/AutomaticDiscount/records/1/edit`)
  await admin.getByRole('button', { name: 'Save changes', exact: true }).waitFor({ timeout: 30000 })
  const assertConfigSaved = async () => {
    await admin.waitForFunction(() => !document.body.innerText.includes('Working…'))
  }
  const enabled = admin.getByRole('checkbox', { name: 'Enable automatic discounts', exact: true })
  assert.equal(await enabled.isChecked(), false)
  await admin.screenshot({ path: `${shots}/admin-disabled.png`, fullPage: true }); console.log('Admin form loaded')
  await enabled.check()
  await admin.getByLabel('Sample cart subtotal').fill('1500')
  await admin.getByRole('button', { name: 'Preview discount', exact: true }).click()
  await admin.getByText('₹225.00 savings.', { exact: false }).waitFor()
  await admin.screenshot({ path: `${shots}/admin-preview.png`, fullPage: true })
  // Preview must not persist activation.
  assert.equal((await prisma.automaticDiscount.findUnique({ where: { id: 1 } })).enabled, false)
  await admin.getByRole('button', { name: 'Save changes', exact: true }).click()
  await admin.getByText('Automatic discounts saved.', { exact: true }).waitFor()
  assert.equal((await prisma.automaticDiscount.findUnique({ where: { id: 1 } })).enabled, true)
  console.log('Admin preview and save passed')
  const customer = await prisma.customer.findUnique({ where: { phone: '9999900411' } })
  const product = await prisma.product.findUnique({ where: { slug: 'discount-fruit' } })
  await replaceCart(customer.id, [{ slug: product.slug, quantity: 1 }])
  await prisma.setting.update({ where: { id: 1 }, data: { firstThreeMorningEnabled: false } })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } })
  const page = await context.newPage()
  page.on('pageerror', (error) => { errors.push(error.message); console.log('PAGE ERROR', error.message) })
  page.on('console', (message) => { if (message.type() === 'error') console.log('CONSOLE', message.text()) })
  page.on('requestfailed', (request) => console.log('REQUEST FAILED', request.url(), request.failure()?.errorText))
  const quotes = []
  page.on('response', async (response) => { if (response.url().endsWith('/checkout/quote') && response.ok()) quotes.push(await response.json()) })
  await page.addInitScript(({ customer, token, product }) => {
    localStorage.setItem('tokri_user', JSON.stringify({ id: customer.id, name: customer.name, phone: customer.phone, token }))
    localStorage.setItem(`tokri_selected_address_${customer.phone}`, 'discount-address')
    localStorage.setItem('tokri_cart_v1', JSON.stringify([{ id: product.slug, name: product.name, priceValue: Number(product.priceValue), quantity: 1, weight: '1 kg' }]))
  }, { customer, token: signCustomerToken(customer), product })
  await page.goto(`${web}/cart`)
  await page.getByText('Automatic discount (15%)', { exact: true }).filter({ visible: true }).first().waitFor({ timeout: 30000 }).catch(async (error) => { console.log(await page.locator('body').innerText()); console.log('QUOTES', quotes); await page.screenshot({ path: '/tmp/tokri-discounts-browser-failure.png' }); throw error })
  await page.getByText('−₹225.00', { exact: true }).filter({ visible: true }).first().waitFor()
  await page.screenshot({ path: `${shots}/cart-discount.png`, fullPage: true })
  await page.goto(`${web}/checkout`)
  await page.getByText('Automatic discount (15%)', { exact: true }).waitFor({ timeout: 30000 })
  await page.getByText('−₹225.00', { exact: true }).waitFor()
  await page.screenshot({ path: `${shots}/checkout-discount.png`, fullPage: true })
  assert.equal(quotes.at(-1).totals.grandTotal, 1302)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: `${shots}/checkout-mobile.png`, fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1050 })
  await replaceCart(customer.id, [{ slug: product.slug, quantity: 1 }, { slug: 'discount-dry', quantity: 1 }])
  await page.reload()
  await page.getByText('−₹300.00', { exact: true }).waitFor()
  await page.getByText('₹21.25', { exact: true }).waitFor()
  await page.screenshot({ path: `${shots}/checkout-mixed-gst.png`, fullPage: true })
  await replaceCart(customer.id, [{ slug: product.slug, quantity: 1 }])
  await page.reload()
  await page.getByText('−₹225.00', { exact: true }).waitFor()
  // Save changed tiers through the real admin form and observe the already-open checkout.
  await admin.getByLabel('Percentage 3', { exact: true }).fill('12')
  await admin.getByRole('button', { name: 'Save changes', exact: true }).click()
  await admin.getByRole('button', { name: 'Save changes', exact: true }).waitFor({ state: 'visible' })
  await assertConfigSaved()
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await page.getByText('Automatic discount (12%)', { exact: true }).waitFor({ timeout: 30000 })
  await page.getByText('−₹180.00', { exact: true }).waitFor()
  // Disable through admin and confirm it disappears without a site rebuild.
  await enabled.uncheck()
  await admin.getByRole('button', { name: 'Save changes', exact: true }).click()
  await admin.getByRole('button', { name: 'Save changes', exact: true }).waitFor({ state: 'visible' })
  await assertConfigSaved()
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await page.getByText('Automatic discount (12%)', { exact: true }).waitFor({ state: 'hidden', timeout: 30000 })
  assert.equal(quotes.at(-1).totals.discount, 0)
  assert.deepEqual(errors, [])
  console.log('PASS: real AdminJS login, preview, save, cart and checkout API rendering, live admin edits, disable; no browser exceptions.')
} finally {
  const config = await prisma.automaticDiscount.findUnique({ where: { id: 1 } })
  await prisma.automaticDiscount.update({ where: { id: 1 }, data: { enabled: false, tiers: config.tiers.map((tier, index) => index === 2 ? { ...tier, percentage: 15 } : tier) } })
  await browser.close(); await prisma.$disconnect()
}
