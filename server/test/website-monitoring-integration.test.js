import { test } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'
import { randomUUID } from 'node:crypto'

test('website monitoring across React Router and Next.js, live debug controls and readable UI', { skip: !process.env.MONITORING_WEBSITE_E2E, timeout: 180000 }, async t => {
  const { root } = await import('./helpers/isolation.js')
  Object.assign(process.env, { CLIENT_URL: 'http://127.0.0.1:5222', APP_URL: 'http://127.0.0.1:5230', API_URL: 'http://127.0.0.1:33380' })
  const { prisma } = await import('../src/lib/prisma.js')
  const { default: express } = await import('express')
  const { default: apiRouter } = await import('../src/routes/api.js')
  const { default: websiteRouter } = await import('../src/monitoring/website.js')
  const { buildAdminRouter } = await import('../src/admin/index.js')
  const { requestLogging, startCriticalOutbox, workerCall, closeMonitoring, setDebug } = await import('../src/monitoring/index.js')
  const { errorHandler } = await import('../src/middleware/errorHandler.js')
  const { signCustomerToken } = await import('../src/services/jwt.js')
  const { chromium } = await import('playwright-core')
  await prisma.user.update({ where: { username: 'review-admin' }, data: { role: 'super_admin', name: 'Monitoring Test Admin' } })
  const customer = await prisma.customer.create({ data: { phone: '9999900413', name: 'Synthetic Website Customer', addresses: [{ id: 'website-test-address', label: 'Home', name: 'Synthetic Website Customer', phone: '9999900413', line1: 'Test house', line2: 'Test area', city: 'Delhi', state: 'Delhi', pincode: '110001' }] } })
  const apple = await prisma.product.findUnique({ where: { slug: 'apple' } })
  await prisma.cart.create({ data: { customerId: customer.id, items: { create: [{ productId: apple.id, quantity: 8 }] } } })
  await prisma.coupon.create({ data: { code: 'WEBSITE5', type: 'percent', value: 5, minCart: 0, showAtCheckout: true, isActive: true } })
  const token = signCustomerToken(customer)
  const { admin, adminRouter } = await buildAdminRouter({ watch: false })
  await startCriticalOutbox()
  const app = express(); app.use(requestLogging); app.use('/api/v1/monitoring', websiteRouter); app.use(admin.options.rootPath, adminRouter); app.use('/api/v1', express.json(), apiRouter); app.use(errorHandler)
  const server = await new Promise(resolve => { const current = app.listen(33380, '127.0.0.1', () => resolve(current)) })
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  context.setDefaultTimeout(15000)
  await context.route('**/*', route => ['localhost', '127.0.0.1'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
  const page = await context.newPage(), captured = [], browserErrors = []
  page.on('pageerror', error => browserErrors.push(error.message))
  page.on('response', response => { if (response.url().endsWith('/monitoring/stream')) browserErrors.push(`Debug stream response: ${response.status()}`) })
  page.on('requestfailed', request => browserErrors.push(`${request.method()} ${request.url().split('?')[0]} ${request.failure()?.errorText}`))
  page.on('request', request => { if (request.url().endsWith('/api/v1/monitoring/events')) captured.push(JSON.parse(request.postData())) })
  const rows = async query => { await workerCall('flush'); return (await workerCall('read', { ...query, perPage: 100 })).rows }
  const waitFor = async (predicate, message) => { const start = performance.now(); while (!(await predicate())) { if (performance.now() - start > 15000) throw new Error(message); await new Promise(resolve => setTimeout(resolve, 100)) } }
  let cookie
  const control = async action => {
    const response = await fetch(`http://127.0.0.1:33380${admin.options.rootPath}/api/pages/logs`, { method: 'POST', headers: { cookie, 'content-type': 'application/json', 'x-tokri-monitoring': '1', 'sec-fetch-site': 'same-origin' }, body: JSON.stringify({ action, minutes: 1 }) })
    assert.equal(response.status, 200); return response.json()
  }
  let broken = false
  const check = (name, fn) => t.test(name, { skip: broken ? 'Earlier browser boundary failed' : false }, async () => { try { await fn() } catch (error) { broken = true; await fs.writeFile(path.join(root, 'browser-errors.txt'), browserErrors.join('\n')); await page.screenshot({ path: path.join(root, 'failure.png'), fullPage: true }).catch(() => {}); await fs.writeFile(path.join(root, 'failure.html'), await page.content()).catch(() => {}); throw error } })
  try {
    await check('authenticated Super Admin control session and website debug OFF by default', async () => {
      await page.goto(`http://127.0.0.1:33380${admin.options.rootPath}/login`)
      await page.locator('input[name=email]').fill('review-admin'); await page.locator('input[name=password]').fill('Isolated-review-password-123')
      await Promise.all([page.waitForURL(`http://127.0.0.1:33380${admin.options.rootPath}`), page.locator('button[type=submit]').click()])
      cookie = (await context.cookies()).map(value => `${value.name}=${value.value}`).join('; ')
      await page.addInitScript(user => localStorage.setItem('tokri_user', JSON.stringify(user)), { id: customer.id, name: customer.name, phone: customer.phone, token })
      await page.goto('http://127.0.0.1:5222/shop?token=PRIVATE_QUERY&phone=9999900413', { waitUntil: 'domcontentloaded' })
      await page.evaluate(() => { window.__originalFetch = window.fetch; window.__sameDocument = true })
      await waitFor(async () => (await rows({ category: 'website' })).some(row => row.pagePath === '/shop'), 'website visit was not delivered')
      assert.equal((await rows({ category: 'debug' })).length, 0)
      assert.equal(await page.evaluate(() => window.fetch === window.__originalFetch), true)
    })
    await check('React Router navigation is recorded once without query strings or API/HTML duplicates', async () => {
      await page.getByText('Apple', { exact: true }).first().click()
      await page.waitForURL('**/product/apple')
      assert.equal(await page.evaluate(() => window.__sameDocument), true)
      await waitFor(async () => (await rows({ category: 'website' })).some(row => row.pagePath === '/product/apple'), 'product visit missing')
      const visits = await rows({ category: 'website' })
      assert.equal(visits.filter(row => row.pagePath === '/shop').length, 1)
      assert.equal(visits.filter(row => row.pagePath === '/product/apple').length, 1)
      assert.equal(visits.find(row => row.pagePath === '/product/apple').navigationType, 'client')
      for (const row of visits) { assert.equal(row.actorId, undefined); assert.equal(row.ip, undefined); assert.ok(!JSON.stringify(row).includes('PRIVATE_QUERY')) }
    })
    await check('live enable activates frontend diagnostics, real cart actions and sanitized frontend/backend failures', async () => {
      await control('enable')
      await page.waitForFunction(() => window.fetch !== window.__originalFetch)
      await page.goto('http://127.0.0.1:5222/shop', { waitUntil: 'domcontentloaded' })
      await page.getByRole('button', { name: 'ADD', exact: true }).first().click()
      await page.evaluate(async () => {
        await fetch('/api/v1/products/missing-product?token=PRIVATE_QUERY').catch(() => {})
        window.dispatchEvent(new ErrorEvent('error', { message: 'password=PRIVATE_PASSWORD otp=PRIVATE_OTP' }))
        window.dispatchEvent(new PromiseRejectionEvent('unhandledrejection', { promise: Promise.resolve(), reason: 'PRIVATE_REJECTION' }))
        const image = document.createElement('img'); image.src = '/uploads/products/missing-product-image.png'; document.body.appendChild(image)
      })
      await waitFor(async () => (await rows({ category: 'debug' })).some(row => row.event === 'cart.added' && row.product), 'named cart event missing')
      await waitFor(async () => (await rows({ category: 'debug' })).some(row => row.event === 'frontend.resource.failed'), 'resource error missing')
      const debug = await rows({ category: 'debug' })
      for (const event of ['frontend.api.failed', 'frontend.error', 'frontend.promise.failed', 'request.timing']) assert.ok(debug.some(row => row.event === event), event)
      const failure = debug.find(row => row.event === 'frontend.api.failed')
      assert.ok(failure.relatedRequestId)
      assert.ok((await rows({ category: 'api' })).some(row => row.requestId === failure.relatedRequestId))
    })
    await check('cart quantity, coupon and delivery interactions are captured without recording private values', async () => {
      await page.goto('http://127.0.0.1:5222/cart', { waitUntil: 'domcontentloaded' })
      await page.getByRole('button', { name: '+', exact: true }).first().click()
      await page.getByRole('button', { name: 'Proceed to checkout', exact: true }).click()
      await page.waitForURL('**/checkout')
      await page.getByRole('radio', { name: /express|same.day|emergency/i }).check()
      await page.getByRole('button', { name: 'Apply', exact: true }).first().click()
      await waitFor(async () => (await rows({ category: 'debug' })).some(row => row.event === 'coupon.applied'), 'coupon diagnostic missing')
      const debug = await rows({ category: 'debug' })
      assert.ok(debug.some(row => row.event === 'cart.quantity.changed'))
      assert.ok(debug.some(row => row.event === 'delivery.selected'))
      const data = JSON.stringify(captured)
      for (const secret of [token, customer.phone, 'PRIVATE_QUERY', 'PRIVATE_PASSWORD', 'PRIVATE_OTP', 'PRIVATE_REJECTION']) assert.ok(!data.includes(secret), secret)
    })
    await check('live disable removes optional collectors immediately and rejects stale batches', async () => {
      const state = await fetch('http://127.0.0.1:33380/api/v1/monitoring/status').then(response => response.json())
      await control('disable')
      await page.evaluate(() => { window.__offFetch = window.fetch })
      await page.waitForTimeout(200)
      const before = (await rows({ category: 'debug' })).length
      await page.evaluate(async () => { await fetch('/api/v1/products/missing-after-disable').catch(() => {}); window.dispatchEvent(new ErrorEvent('error', { message: 'PRIVATE_OFF' })) })
      const stale = await fetch('http://127.0.0.1:33380/api/v1/monitoring/events', { method: 'POST', headers: { 'content-type': 'application/json', origin: 'http://127.0.0.1:5222' }, body: JSON.stringify({ generation: state.generation, events: [{ id: randomUUID(), event: 'cart.added', path: '/cart', productRef: 'apple' }] }) }).then(response => response.json())
      assert.equal(stale.accepted, 0)
      await page.waitForTimeout(1300)
      assert.equal((await rows({ category: 'debug' })).length, before)
    })
    await check('Next.js route commits log once while prefetch/RSC work does not count as visits', async () => {
      await page.goto('http://127.0.0.1:5230/product/apple', { waitUntil: 'domcontentloaded' })
      await page.evaluate(() => { window.__nextDocument = true })
      await waitFor(async () => (await rows({ category: 'website' })).filter(row => row.pagePath === '/product/apple').length === 2, 'Next initial visit missing')
      const before = (await rows({ category: 'website' })).length
      const link = page.locator('a[href^="/shop?"]').first()
      await link.hover(); await page.waitForTimeout(1300)
      assert.equal((await rows({ category: 'website' })).length, before, 'prefetch must not create a visit')
      await link.click(); await page.waitForURL('**/shop?**')
      assert.equal(await page.evaluate(() => window.__nextDocument), true, 'Next transition must preserve the document')
      await waitFor(async () => (await rows({ category: 'website' })).length === before + 1, 'Next client visit missing or duplicated')
      const latest = (await rows({ category: 'website' }))[0]
      assert.equal(latest.pagePath, '/shop'); assert.equal(latest.navigationType, 'client'); assert.equal(latest.httpStatus, undefined)
      await page.goBack()
      await page.waitForURL('**/product/apple')
      await waitFor(async () => (await rows({ category: 'website' })).length === before + 2, 'Next back navigation missing')
      assert.equal((await rows({ category: 'website' }))[0].navigationType, 'back_forward')
      await page.locator('a[href^="/shop?"]').first().click()
      await page.waitForURL('**/shop?**')
      await waitFor(async () => (await rows({ category: 'website' })).length === before + 3, 'Next repeat navigation missing')
      assert.equal((await rows({ category: 'website' }))[0].navigationType, 'client')
    })
    await check('frontend deadline stops diagnostics without waiting for another control request', async () => {
      await page.clock.install()
      await page.evaluate(() => { window.__beforeExpiryFetch = window.fetch })
      await control('enable')
      await page.waitForFunction(() => window.fetch !== window.__beforeExpiryFetch)
      await page.route('**/p/diagnostic-failure', route => route.fulfill({ status: 503, body: 'Simulated page transport failure' }))
      await page.evaluate(async () => {
        await fetch('/api/v1/products/missing-next-product')
        await fetch('/p/diagnostic-failure', { headers: { rsc: '1' } })
      })
      await waitFor(async () => (await rows({ category: 'debug' })).some(row => row.event === 'frontend.page.failed'), 'Next page-loading diagnostic missing')
      // The server supplies the real deadline. Advance only this browser's clock;
      // backend expiry is independently exercised in website-monitoring.test.js.
      await page.clock.fastForward(61000)
      assert.equal(await page.evaluate(() => window.fetch === window.__beforeExpiryFetch), true)
      const before = captured.flatMap(packet => packet.events).filter(row => row.event === 'frontend.error').length
      await page.evaluate(() => window.dispatchEvent(new ErrorEvent('error', { message: 'PRIVATE_EXPIRED' })))
      await page.clock.fastForward(1500)
      assert.equal(captured.flatMap(packet => packet.events).filter(row => row.event === 'frontend.error').length, before)
      await control('disable')
    })
    await check('readable category UI, daily selection, status filters and responsive evidence', async () => {
      const yesterday = new Date(Date.now() - 86400000)
      const previousDay = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Kolkata' }).format(yesterday)
      await workerCall('deliver', { category: 'website', record: { eventId: randomUUID(), timestamp: yesterday.toISOString(), event: 'website.navigation', origin: 'browser', page: 'Checkout', pagePath: '/checkout', status: 'observed' } })
      await page.goto(`http://127.0.0.1:33380${admin.options.rootPath}/pages/logs`)
      await page.getByRole('button', { name: 'Website visits', exact: true }).click()
      await page.getByText('Customer opened the checkout page.', { exact: true }).first().waitFor()
      await page.getByLabel('Status / outcome', { exact: true }).selectOption('Successful')
      await page.getByRole('button', { name: 'Apply filters', exact: true }).click()
      await page.getByRole('button', { name: 'Apply filters', exact: true }).waitFor({ state: 'visible' })
      await waitFor(() => page.getByRole('button', { name: 'Apply filters', exact: true }).isEnabled(), 'filters did not finish')
      const previous = page.getByRole('button', { name: 'Previous day', exact: true })
      await previous.click()
      await waitFor(() => previous.isEnabled(), 'daily filter did not finish')
      await previous.click()
      await waitFor(async () => await page.getByLabel('Date (IST)', { exact: true }).inputValue() === previousDay && await previous.isEnabled() === false, 'previous day was not selected')
      await page.getByRole('button', { name: 'Next day', exact: true }).click()
      await waitFor(() => page.getByRole('button', { name: 'Apply filters', exact: true }).isEnabled(), 'next day did not finish')
      assert.equal(await page.locator('.tokri-monitoring pre,.tokri-monitoring code').count(), 0)
      assert.ok(!(await page.locator('tbody').innerText()).includes('Logs viewed'))
      await page.screenshot({ path: path.join(root, 'after-desktop.png'), fullPage: false })
      await page.setViewportSize({ width: 390, height: 844 })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
      await page.screenshot({ path: path.join(root, 'after-mobile.png'), fullPage: true })
      await page.locator('tbody tr').first().scrollIntoViewIfNeeded()
      await page.screenshot({ path: path.join(root, 'after-mobile-rows.png'), fullPage: false })
    })
  } finally {
    setDebug(false); await browser.close(); await new Promise(resolve => server.close(resolve)); await closeMonitoring(); await prisma.$disconnect()
  }
})
